// Generates src/runtime/core/unicodeTables.inc from the Unicode Character
// Database files in tools/unicodegen/ucd (Unicode 16.0.0):
//   GraphemeBreakProperty.txt            Grapheme_Cluster_Break
//   emoji-data.txt                       Extended_Pictographic
//   DerivedCoreProperties-InCB.txt       Indic_Conjunct_Break (the InCB lines of
//                                        DerivedCoreProperties.txt)
//
// Build and run (from a VS developer prompt, in the repository root):
//   cl /std:c++20 /EHsc /O2 tools\unicodegen\unicodegen.cpp /Fe:unicodegen.exe
//   unicodegen.exe tools\unicodegen\ucd src\runtime\core\unicodeTables.inc
//
// The output is a sorted table of codepoint ranges, each with packed properties:
//   bits 0-3  Grapheme_Cluster_Break (see GraphemeBreak in graphemes.h)
//   bit  4    Extended_Pictographic
//   bits 5-6  Indic_Conjunct_Break: 1 Linker, 2 Consonant, 3 Extend

#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace {

constexpr uint32_t maxCodepoint = 0x10FFFF;

const std::map<std::string, uint8_t> breakValues = {
    {"Other", 0}, {"CR", 1}, {"LF", 2}, {"Control", 3}, {"Extend", 4}, {"ZWJ", 5}, {"Regional_Indicator", 6},
    {"Prepend", 7}, {"SpacingMark", 8}, {"L", 9}, {"V", 10}, {"T", 11}, {"LV", 12}, {"LVT", 13},
};

std::string trim(const std::string& text)
{
    size_t begin = text.find_first_not_of(" \t");
    size_t end = text.find_last_not_of(" \t\r");
    return begin == std::string::npos ? "" : text.substr(begin, end - begin + 1);
}

// Calls `handle(first, last, fields)` for every data line: "XXXX..YYYY ; a ; b # comment".
template <class Handle>
bool readRanges(const std::string& path, Handle handle)
{
    std::ifstream in(path);
    if (!in) {
        std::cerr << "unicodegen: can't read " << path << "\n";
        return false;
    }
    std::string line;
    while (std::getline(in, line)) {
        line = line.substr(0, line.find('#'));
        if (trim(line).empty()) {
            continue;
        }
        std::vector<std::string> fields;
        std::stringstream parts(line);
        std::string field;
        while (std::getline(parts, field, ';')) {
            fields.push_back(trim(field));
        }
        std::string range = fields[0];
        size_t dots = range.find("..");
        uint32_t first = std::stoul(range.substr(0, dots), nullptr, 16);
        uint32_t last = dots == std::string::npos ? first : std::stoul(range.substr(dots + 2), nullptr, 16);
        handle(first, last, fields);
    }
    return true;
}

}

int main(int argc, char** argv)
{
    if (argc != 3) {
        std::cerr << "usage: unicodegen <ucd directory> <output .inc>\n";
        return 2;
    }
    std::string dir = argv[1];
    std::vector<uint8_t> props(maxCodepoint + 1, 0);

    bool ok = readRanges(dir + "/GraphemeBreakProperty.txt", [&](uint32_t first, uint32_t last, const std::vector<std::string>& f) {
        uint8_t value = breakValues.at(f[1]);
        for (uint32_t c = first; c <= last; ++c) {
            props[c] = static_cast<uint8_t>((props[c] & ~0x0F) | value);
        }
    });
    ok = ok && readRanges(dir + "/emoji-data.txt", [&](uint32_t first, uint32_t last, const std::vector<std::string>& f) {
        if (f[1] == "Extended_Pictographic") {
            for (uint32_t c = first; c <= last; ++c) {
                props[c] |= 0x10;
            }
        }
    });
    ok = ok && readRanges(dir + "/DerivedCoreProperties-InCB.txt", [&](uint32_t first, uint32_t last, const std::vector<std::string>& f) {
        if (f.size() < 3 || f[1] != "InCB") {
            return;
        }
        uint8_t value = f[2] == "Linker" ? 1 : f[2] == "Consonant" ? 2 : f[2] == "Extend" ? 3 : 0;
        for (uint32_t c = first; c <= last; ++c) {
            props[c] = static_cast<uint8_t>((props[c] & ~0x60) | (value << 5));
        }
    });
    if (!ok) {
        return 1;
    }

    struct Range {
        uint32_t first;
        uint32_t last;
        uint8_t props;
    };
    std::vector<Range> ranges;
    for (uint32_t c = 0; c <= maxCodepoint; ++c) {
        if (props[c] == 0) {
            continue;
        }
        if (!ranges.empty() && ranges.back().last + 1 == c && ranges.back().props == props[c]) {
            ranges.back().last = c;
        }
        else {
            ranges.push_back({c, c, props[c]});
        }
    }

    std::ofstream out(argv[2], std::ios::binary);
    out << "// Generated by tools/unicodegen from the Unicode 16.0.0 UCD. Do not edit.\n";
    out << "// { first, last, properties } sorted by codepoint; codepoints not listed have properties 0.\n";
    out << "constexpr uint32_t unicodeRangeCount = " << ranges.size() << ";\n";
    out << "constexpr UnicodeRange unicodeRanges[unicodeRangeCount] = {\n";
    char text[64];
    for (const Range& r : ranges) {
        std::snprintf(text, sizeof(text), "    {0x%05X, 0x%05X, 0x%02X},\n", r.first, r.last, r.props);
        out << text;
    }
    out << "};\n";
    std::cout << "unicodegen: " << ranges.size() << " ranges\n";
    return 0;
}
